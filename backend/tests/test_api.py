class TestUpdateInvoice:
    def test_put_updates_existing_invoice_same_id(self, client, auth_ctx, sample_native_pdf, sample_scanned_pdf):
        matter_id = auth_ctx["make_matter"]()
        with open(sample_native_pdf, "rb") as f:
            create = client.post(
                "/invoices/submit",
                headers=auth_ctx["headers"],
                data={"matter_id": matter_id},
                files={"file": ("sample_invoice_native.pdf", f, "application/pdf")},
            )
        assert create.status_code == 200
        invoice_id = create.json()["invoice_id"]

        with open(sample_scanned_pdf, "rb") as f:
            r = client.put(
                f"/invoices/{invoice_id}",
                data={"matter_id": matter_id},
                files={"file": ("sample_invoice_scanned.pdf", f, "application/pdf")},
            )
        assert r.status_code == 200
        assert r.json()["invoice"]["invoice_id"] == invoice_id

        listing = client.get("/invoices", headers=auth_ctx["headers"]).json()
        matches = [inv for inv in listing if inv["invoice_id"] == invoice_id]
        assert len(matches) == 1

    def test_put_nonexistent_invoice_returns_404(self, client, auth_ctx, sample_native_pdf):
        matter_id = auth_ctx["make_matter"]()
        with open(sample_native_pdf, "rb") as f:
            r = client.put(
                "/invoices/999999",
                data={"matter_id": matter_id},
                files={"file": ("sample_invoice_native.pdf", f, "application/pdf")},
            )
        assert r.status_code == 404


