class TestDuplicateSubmission:
    def test_second_submission_of_same_invoice_no_and_matter_returns_409(self, client, auth_ctx, sample_native_pdf):
        """
        Reproduces the reported bug via the actual HTTP endpoint (QA
        findings bug #5). Duplicate detection is based on invoice_no +
        matter_id, and invoice_no is only known after extraction runs —
        see app/api/invoices.py's module docstring.
        """
        matter_id = auth_ctx["make_matter"]()
        with open(sample_native_pdf, "rb") as f:
            first = client.post(
                "/invoices/submit",
                headers=auth_ctx["headers"],
                data={"matter_id": matter_id},
                files={"file": ("sample_invoice_native.pdf", f, "application/pdf")},
            )
        assert first.status_code == 200

        with open(sample_native_pdf, "rb") as f:
            second = client.post(
                "/invoices/submit",
                headers=auth_ctx["headers"],
                data={"matter_id": matter_id},
                files={"file": ("sample_invoice_native.pdf", f, "application/pdf")},
            )
        assert second.status_code == 409
        body = second.json()
        assert "already exists" in body["detail"]
        assert "inv_changes" in body
        assert isinstance(body["inv_changes"], dict)

    def test_duplicate_rejection_does_not_create_a_second_row(self, client, auth_ctx, sample_native_pdf):
        matter_id = auth_ctx["make_matter"]()
        with open(sample_native_pdf, "rb") as f:
            first = client.post(
                "/invoices/submit",
                headers=auth_ctx["headers"],
                data={"matter_id": matter_id},
                files={"file": ("sample_invoice_native.pdf", f, "application/pdf")},
            )
        assert first.status_code == 200
        invoice_id = first.json()["invoice_id"]

        with open(sample_native_pdf, "rb") as f:
            second = client.post(
                "/invoices/submit",
                headers=auth_ctx["headers"],
                data={"matter_id": matter_id},
                files={"file": ("sample_invoice_native.pdf", f, "application/pdf")},
            )
        assert second.status_code == 409

        r = client.get(f"/invoices/{invoice_id}", headers=auth_ctx["headers"])
        assert r.status_code == 200


